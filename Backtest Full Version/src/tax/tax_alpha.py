"""
Tax-Alpha Engine.
Analyzes the exact compounding wealth advantage ("Tax Alpha") generated by
tax-efficient structural implementation (e.g. Ireland UCITS CSPX vs US-domiciled VOO/SPY).
Models dividend withholding leakage, fund expense ratios (TER), distribution drag,
internal reinvestment, multi-horizon wealth differentials, and sensitivity matrices.
"""

from dataclasses import dataclass
from typing import Dict, List, Optional, Tuple, Any
import numpy as np
import pandas as pd

from .tax_engine import TaxEngine, AssetTaxConfig


@dataclass
class CSPXTaxAlphaComparison:
    """
    Dedicated quantitative comparison between CSPX (Ireland UCITS) and VOO/SPY (US Domiciled).
    Transparently models dividend withholding tax, fund expense ratios, and cash drag.
    """
    initial_investment: float
    annual_sp500_gross_return: float
    dividend_yield: float
    monthly_contribution: float = 0.0
    contribution_growth_rate: float = 0.0
    currency_symbol: str = "$"

    cspx_withholding_tax: float = 0.15  # US-Ireland treaty rate at fund level
    voo_withholding_tax: float = 0.30  # US statutory NRA withholding tax rate
    cspx_ter: float = 0.0007  # iShares Core S&P 500 TER: 0.07%
    voo_ter: float = 0.0003  # Vanguard S&P 500 ETF TER: 0.03%
    include_ter: bool = False  # Set True to incorporate expense ratio differential

    def compute_horizon_tax_alpha(self, horizons: Optional[List[int]] = None) -> pd.DataFrame:
        """
        Compute horizon wealth accumulation comparison across milestones.
        """
        if horizons is None:
            horizons = [5, 10, 15, 20, 30]

        sym = self.currency_symbol
        r_gross = self.annual_sp500_gross_return
        dy = self.dividend_yield

        ter_cspx = self.cspx_ter if self.include_ter else 0.0
        ter_voo = self.voo_ter if self.include_ter else 0.0

        r_cspx = r_gross - (dy * self.cspx_withholding_tax) - ter_cspx
        r_voo = r_gross - (dy * self.voo_withholding_tax) - ter_voo

        rows = []
        for h in horizons:
            w_gross = self.initial_investment
            w_cspx = self.initial_investment
            w_voo = self.initial_investment
            total_contrib = self.initial_investment

            for yr in range(1, h + 1):
                annual_contrib = self.monthly_contribution * 12.0 * ((1.0 + self.contribution_growth_rate) ** (yr - 1))
                w_gross = (w_gross + annual_contrib) * (1.0 + r_gross)
                w_cspx = (w_cspx + annual_contrib) * (1.0 + r_cspx)
                w_voo = (w_voo + annual_contrib) * (1.0 + r_voo)
                total_contrib += annual_contrib

            drag_cspx = w_gross - w_cspx
            drag_voo = w_gross - w_voo
            tax_alpha_dollars = w_cspx - w_voo
            tax_alpha_pct = (tax_alpha_dollars / max(1.0, w_voo)) * 100.0
            ann_alpha_bps = (r_cspx - r_voo) * 10000.0

            rows.append({
                "Horizon": f"{h} Years",
                "Gross Wealth": f"{sym}{w_gross:,.0f}",
                "CSPX (Ireland UCITS)": f"{sym}{w_cspx:,.0f}",
                "VOO (US Domiciled)": f"{sym}{w_voo:,.0f}",
                "VOO Tax Drag (Loss)": f"-{sym}{drag_voo:,.0f}",
                "CSPX Tax Drag (Loss)": f"-{sym}{drag_cspx:,.0f}",
                "Tax Alpha (Net Gain)": f"+{sym}{tax_alpha_dollars:,.0f}",
                "Tax Alpha (% Boost)": f"+{tax_alpha_pct:.2f}%",
                "Annualized Alpha": f"+{ann_alpha_bps:.1f} bps/yr"
            })

        return pd.DataFrame(rows).set_index("Horizon")

    def compute_sensitivity_matrix(
        self,
        dividend_yields: Optional[List[float]] = None,
        gross_returns: Optional[List[float]] = None,
        horizon_years: int = 15
    ) -> pd.DataFrame:
        """
        Sensitivity analysis varying dividend yield and gross returns over a fixed horizon.
        Returns a DataFrame showing Net Dollar Tax Alpha (CSPX Wealth - VOO Wealth).
        """
        if dividend_yields is None:
            dividend_yields = [0.010, 0.0125, 0.015, 0.0175, 0.020, 0.025]
        if gross_returns is None:
            gross_returns = [0.06, 0.08, 0.10, 0.12]

        matrix = {}
        for dy in dividend_yields:
            row_vals = {}
            for gr in gross_returns:
                r_c = gr - (dy * self.cspx_withholding_tax)
                r_v = gr - (dy * self.voo_withholding_tax)

                w_c = self.initial_investment
                w_v = self.initial_investment
                for yr in range(1, horizon_years + 1):
                    ann_contrib = self.monthly_contribution * 12.0 * ((1.0 + self.contribution_growth_rate) ** (yr - 1))
                    w_c = (w_c + ann_contrib) * (1.0 + r_c)
                    w_v = (w_v + ann_contrib) * (1.0 + r_v)

                alpha_gain = w_c - w_v
                row_vals[f"Return {gr*100:.0f}%"] = f"{self.currency_symbol}{alpha_gain:,.0f}"
            matrix[f"Div Yield {dy*100:.2f}%"] = row_vals

        df_sens = pd.DataFrame(matrix).T
        df_sens.index.name = f"Sensitivity Grid ({horizon_years}Y Horizon)"
        return df_sens


class TaxAlphaEngine:
    """
    Portfolio-level and asset-level Tax Alpha evaluator.
    """

    def __init__(self, tax_engine: Optional[TaxEngine] = None):
        self.tax_engine = tax_engine or TaxEngine()

    def evaluate_cspx_advantage(
        self,
        initial_investment: float = 10_000.0,
        annual_gross_return: float = 0.10,
        dividend_yield: float = 0.015,
        monthly_contribution: float = 500.0,
        contribution_growth_rate: float = 0.10,
        currency_symbol: str = "$",
        include_ter: bool = False
    ) -> CSPXTaxAlphaComparison:
        return CSPXTaxAlphaComparison(
            initial_investment=initial_investment,
            annual_sp500_gross_return=annual_gross_return,
            dividend_yield=dividend_yield,
            monthly_contribution=monthly_contribution,
            contribution_growth_rate=contribution_growth_rate,
            currency_symbol=currency_symbol,
            include_ter=include_ter
        )
